// Адресът на продукт в сайта — /menu/<slug>.
//
// ЗАЩО СЪЩЕСТВУВА ТОЗИ ФАЙЛ: до 27.08 всеки нов продукт получаваше адрес
// „produkt-“ + шест случайни знака. Докато продуктите живееха само в общото
// меню, това нямаше значение — адресът никъде не се виждаше. Щом всеки продукт
// има собствена страница, адресът става това, което Google чете и човекът
// вижда: /menu/produkt-4lzcvy не казва нищо, /menu/torta-garash-krem-pistacho
// казва всичко.
//
// ⚠️ АДРЕСЪТ Е ОБЕЩАНИЕ. Публикуван веднъж, той стои в чужди линкове, в
// историята на браузъра и в индекса на Google. Затова се генерира при
// СЪЗДАВАНЕ и после не се пипа автоматично — преименуването на продукт НЕ
// сменя адреса му. Смяна се прави само ръчно и съзнателно.

// Официалната българска транслитерация (Закон за транслитерацията, 2009).
// Същата, по която са писани заварените добри адреси — „shokoladova“, „fastachen“.
const BG: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ж: "zh", з: "z", и: "i",
  й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s",
  т: "t", у: "u", ф: "f", х: "h", ц: "ts", ч: "ch", ш: "sh", щ: "sht",
  ъ: "a", ь: "y", ю: "yu", я: "ya",
};

/** „Торта „Гараш“ крем Пистачо“ → „torta-garash-krem-pistacho“ */
export function slugify(input: string): string {
  const out = [...input.toLowerCase().normalize("NFC")]
    .map((ch) => BG[ch] ?? ch)
    .join("")
    // латиница с ударения → без (за евентуални чужди имена в менюто)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
  return out || "produkt";
}

/**
 * Прави адреса уникален спрямо вече заетите: „halva“ → „halva-2“ → „halva-3“.
 * Базата пази UNIQUE(slug) и това е истинската защита — тук само подбираме
 * разумен кандидат, за да не гърми записът излишно.
 */
export function uniqueSlug(base: string, taken: Iterable<string>): string {
  const used = new Set(taken);
  if (!used.has(base)) return base;
  for (let n = 2; n < 1000; n++) {
    const s = `${base}-${n}`;
    if (!used.has(s)) return s;
  }
  return `${base}-${Date.now()}`;
}
