/**
 * Надписът над името на продуктовата страница — изречението, което казва КАКВО
 * е това, с думите, с които хората търсят. „Протеинова торта" и „торта без захар"
 * не се срещат никъде в имената на продуктите, а точно тях пишат в Google.
 *
 * Продуктът може да има собствен (products.tagline). Без него — по категорията.
 * Отделното поле е нужно, защото категорията лъже за изключенията: тартът е торта,
 * но не е протеинов.
 */
export const DEFAULT_TAGLINE: Record<string, string> = {
  торта: "Протеинова торта без добавена захар",
  // Вафлите се правят основно с лешников крем, не с протеин — „протеинови" подвеждаше.
  вафла: "Вафли без добавена захар",
  халва: "Протеинова халва без добавена захар",
  шейк: "Протеинов шейк без добавена захар",
};

export function taglineFor(p: { tagline?: string | null; category?: string | null }): string | null {
  return p.tagline?.trim() || DEFAULT_TAGLINE[p.category ?? ""] || null;
}
